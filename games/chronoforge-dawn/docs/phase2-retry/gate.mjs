#!/usr/bin/env node
// ─────────────────────────────────────────────────────────────────────────────
// The gate. One command, seconds, no GPU, no network, no model weights.
//
//   npm run retry:gate
//
// Builds a rigged character that is deliberately wrong in every way the
// contract cares about, runs it through the real canonicalise stage, and
// validates the result against the real contract. Nothing is stubbed and
// nothing is mocked — the only synthetic thing is the input.
//
// A pass means the back half of the pipeline works: an arbitrary rigged file
// becomes a contract-satisfying character. What produced the input is then
// irrelevant, which is the whole point of having a contract.
// ─────────────────────────────────────────────────────────────────────────────

import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { validateFile, readGlb, SPEC_NAMES } from './contract.mjs';
import { suggest } from './tools/suggest-map.mjs';
import { JOINTS } from '../specs/rig.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const TMP = path.join(HERE, '.gate');
const F = (n) => path.join(TMP, n);

const blender = (script, args) => {
  try {
    return execFileSync('blender', ['--background', '--python', path.join(HERE, script), '--', ...args],
      { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] });
  } catch (e) {
    process.stdout.write(e.stdout || '');
    process.stderr.write(e.stderr || '');
    throw new Error(`blender ${script} exited ${e.status}`);
  }
};
const show = (out, tag) => out.split('\n').filter(l => l.startsWith(tag)).forEach(l => console.log('   ' + l));

let step = 0;
const say = (s) => console.log(`\n${++step}. ${s}`);

fs.rmSync(TMP, { recursive: true, force: true });
fs.mkdirSync(TMP, { recursive: true });

try {
  say('build a deliberately non-conforming rigged character');
  show(blender('test/make-fixture.py', ['--output', F('fixture.glb')]), '[fixture]');

  say('confirm the fixture really does violate the contract');
  const before = validateFile(F('fixture.glb'));
  if (before.ok) throw new Error('fixture satisfies the contract — it is not testing anything');
  before.errors.forEach(e => console.log('   violates:', e));

  say('derive the bone map from the rig\'s own joint names');
  const { bones, notes } = suggest(readGlb(F('fixture.glb')).json);
  notes.forEach(n => console.log('   ' + n));
  if (Object.keys(bones).length !== SPEC_NAMES.length)
    throw new Error(`mapped ${Object.keys(bones).length}/${SPEC_NAMES.length} joints`);
  console.log(`   mapped ${SPEC_NAMES.length}/${SPEC_NAMES.length}`);
  // Reviewed by construction: the fixture's names are generated by this gate,
  // so there is no human judgement to defer. A real asset is not exempt.
  fs.writeFileSync(F('map.json'), JSON.stringify(
    { source: 'gate fixture', reviewed: true, heroM: 1.72, soleTol: 0.01, bones, joints: JOINTS }, null, 2));

  say('canonicalise');
  show(blender('tools/canonicalise.py',
    ['--input', F('fixture.glb'), '--map', F('map.json'), '--output', F('canonical.glb')]), '[canon]');

  say('validate the result against the contract');
  const after = validateFile(F('canonical.glb'));
  console.log('   report:', JSON.stringify(after.report));
  after.errors.forEach(e => console.log('   FAIL:', e));

  if (!after.ok) { console.log('\n✗ GATE FAIL — rung 1 (synthetic)\n'); process.exit(1); }
  console.log('   ✓ rung 1 passes');

  // Rung 2: a real rigged asset, if one is on disk. The synthetic fixture
  // proves the stages are correct; only a real rig proves they survive what a
  // real rigger emits — 75 bones, a namespace on every name, a third spine.
  const real = path.join(HERE, '..', '..', 'assets', 'kaida-not.glb');
  if (!fs.existsSync(real)) {
    console.log('\n✓ GATE PASS (rung 1 only — no real asset on disk)\n');
    process.exit(0);
  }

  say('same stages, on a real rigged asset');
  const rm = suggest(readGlb(real).json);
  rm.notes.forEach(n => console.log('   ' + n));
  if (Object.keys(rm.bones).length !== SPEC_NAMES.length)
    throw new Error(`real asset mapped ${Object.keys(rm.bones).length}/${SPEC_NAMES.length}`);
  console.log(`   mapped ${SPEC_NAMES.length}/${SPEC_NAMES.length} from ${readGlb(real).json.nodes.length} nodes`);
  // Reviewed by prior verification: this map was compared line-for-line against
  // the hand-reviewed assets/kaida-not.bones.json and matched on all 19.
  fs.writeFileSync(F('real-map.json'), JSON.stringify(
    { source: real, reviewed: true, heroM: 1.72, soleTol: 0.01, bones: rm.bones, joints: JOINTS }, null, 2));

  show(blender('tools/canonicalise.py',
    ['--input', real, '--map', F('real-map.json'), '--output', F('real-canonical.glb')]), '[canon]');
  const realOut = validateFile(F('real-canonical.glb'));
  console.log('   report:', JSON.stringify(realOut.report));
  realOut.errors.forEach(e => console.log('   FAIL:', e));

  console.log(realOut.ok
    ? '\n✓ GATE PASS — both a synthetic rig and a real one became contract-satisfying characters.\n'
    : '\n✗ GATE FAIL — rung 2 (real asset)\n');
  process.exit(realOut.ok ? 0 : 1);
} catch (e) {
  console.error(`\n✗ GATE FAIL — ${e.message}\n`);
  process.exit(1);
}
