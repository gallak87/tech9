// Boot and main loop. THE one integration point.
//
// Lanes are installed here through fixed seams and never reach into each other.
// Every install goes through `installModule`, so a lane that throws — at install
// or in its per-frame tick — is quarantined and the rest of the game keeps
// rendering. Eleven lanes work this repo in parallel; a broken module blanking
// the screen would block every one of them from taking a screenshot.
//
// SHARED CORE. If you need a new seam here, put it in your report as a
// core-change request. Do not edit this file.
