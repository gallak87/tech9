install('progression', installProgression);
install('settlement', installSettlement);

const focus = () => ctx.world?.focus || new THREE.Vector3();

/* Where the shadow map should be centred.
   NOT the camera position — the shadow camera covers ±52 m, and a review shot
   sits 130 m back and 60 m up, which puts the whole subject outside the map and
   silently drops every prop shadow while terrain self-shadowing keeps working.
   That combination reads as "props are pasted on" and is exactly defect 3.
   So: cast the camera's view direction onto the ground plane and centre there. */
const _fwd = new THREE.Vector3();
const _sf = new THREE.Vector3();
function shadowFocus() {
  const f = focus();
  if (!shotMode) return rig.target;
  engine.camera.getWorldDirection(_fwd);
  const cam = engine.camera.position;
  const denom = _fwd.y;
  // Looking level or up: nothing to aim at, so keep the world focus.
  if (denom > -0.05) return f;
  const t = THREE.MathUtils.clamp((f.y - cam.y) / denom, 0, 400);
  _sf.copy(cam).addScaledVector(_fwd, t);
  const half = (ctx.world?.size ?? 240) * 0.5;
  _sf.x = THREE.MathUtils.clamp(_sf.x, -half, half);
  _sf.z = THREE.MathUtils.clamp(_sf.z, -half, half);
  _sf.y = ctx.world?.heightAt ? ctx.world.heightAt(_sf.x, _sf.z) : f.y;
  return _sf;
}

/* ── deterministic stepping ──────────────────────────────────────────────────
   The sim is fixed-step at 120 Hz; frames are not. Rendering the raw variable
   step is how a following camera picks up a stutter that no profiler explains.
   Input is sampled per FRAME, outside the step, because input is a poll of
   devices and not a quantity the sim integrates — and because a paused game
   that stops reading the keyboard can never be un-paused.                    */
const FIXED = 1 / 120;
let acc = 0;
let simTime = 0;
let running = true;
let shotMode = null;

function step(dt) {
  for (const k of ['world', 'traversal', 'actors', 'places', 'battle', 'progression', 'settlement']) {
    modules[k].tick(dt, ctx);
  }
  simTime += dt;
}

function updateScene(dt, moveCamera = true) {
  if (moveCamera) rig.follow(engine.camera, focus(), dt);
  env.update(dt, rig.target);
  modules.fx.tick(dt, ctx);
  modules.audio.tick(dt, ctx);
  modules.ui.tick(dt, ctx);
  ctx.dev?.update();
}

/** Fast-forward the sim to an absolute time without rendering. */
function seekTo(t) {
  const target = Math.max(0, t);
  let guard = 0;
  while (simTime < target - FIXED * 0.5 && guard++ < 500000) step(FIXED);
  updateScene(FIXED);
  return simTime;
}

function frame() {
  requestAnimationFrame(frame);
  const dt = engine.tick();

  if (running && !shotMode) {
    acc += dt;
    let guard = 0;
    while (acc >= FIXED && guard++ < 8) { step(FIXED); acc -= FIXED; }
    updateScene(dt, true);
  } else if (shotMode) {
    applyShot(shotMode, ctx);
    env.update(dt, shadowFocus());
    modules.ui.tick(dt, ctx);
  } else {
    modules.ui.tick(dt, ctx);
  }
  engine.render();
}

/* ── the debug API ───────────────────────────────────────────────────────────
   Every tool in tools/ drives the game through this and nothing else. Keep it
   stable: a rename here breaks thirteen probes at once.                      */
const api = {
  ctx, engine, env, rig, THREE,
  ready: false,
  version: '0.1.0-phase0',
  get shots() { return shotNames(); },
  /** Current named shot, or null. The dev panel hides itself while this is set. */
  get shot() { return shotMode; },
  get modules() { return modules; },

  pause() { running = false; },
  resume() { running = true; },

  /** Fast-forward the fixed-step sim to an absolute time, in seconds. */
  seek(t) { return seekTo(t); },

  /** Advance the sim by N fixed steps. The frame-accurate stepping a probe
   *  needs — never `seek(now + n/120)`, which accumulates float error. */
  step(n = 1) {
    for (let i = 0; i < n; i++) step(FIXED);
    updateScene(FIXED, !shotMode);
    return simTime;
  },

  /** Name a review camera, or null to hand control back to the rig. */
  setShot(name) {
    shotMode = name || null;
    if (shotMode && !SHOTS[shotMode]) { console.warn('[shot] unknown', shotMode); }
    if (shotMode) { running = false; applyShot(shotMode, ctx); }
    else { running = true; rig.reset(focus()); }
    return shotMode;
  },

  /** Hour of day, 0–24. Drives sun, sky, IBL, fog and shadow direction. */
  setTime(hour, opts) { env.setTime(hour, opts); bus.emit('time:changed', { hour: env.hour }); return env.hour; },

  /** Live post knobs. `__DAWN__.post({ exposure: 0.8 })`. */
  post(patch = {}) {
    const p = engine.post;
    if (!p) return null;
    if (patch.exposure != null) p.params.exposure = patch.exposure;
    if (patch.contrast != null) p.params.contrast = patch.contrast;
    if (patch.saturation != null) p.params.saturation = patch.saturation;
    if (patch.vignette != null) p.params.vignette = patch.vignette;
    if (patch.grain != null) p.params.grain = patch.grain;
    if (patch.split != null) p.params.split = patch.split;
    if (patch.bloom) Object.assign(p.params.bloom, patch.bloom);
    if (patch.enable) for (const [k, v] of Object.entries(patch.enable)) p.setEnabled(k, v);
    return { ...p.params, enabled: { ...p.enabled } };
  },

  /** Linear-light histogram. Measure the exposure; do not argue about it. */
  probe(opts) { return engine.post ? engine.post.probe(opts) : null; },

  /** Frame cost against the hard budget, plus per-lane health. */
  stats() {
    const info = engine.renderer.info;
    const s = {
      fps: 1000 / engine.avgFrameMs,
      frameMs: engine.avgFrameMs,
      calls: info.render.calls,
      tris: info.render.triangles,
      programs: info.programs?.length ?? 0,
      textures: info.memory.textures,
      geometries: info.memory.geometries,
      megapixels: +engine.megapixels.toFixed(2),
      quality: engine.qualityName,
      hour: +env.hour.toFixed(2),
      sunElevation: +env.elevation.toFixed(1),
      simTime: +simTime.toFixed(3),
      cameraLocked: rig.assertLocked(),
      modules: moduleReport(modules),
    };
    s.budget = {
      frameMs: { value: +s.frameMs.toFixed(2), limit: BUDGET.frameMs, ok: s.frameMs <= BUDGET.frameMs },
      calls: { value: s.calls, limit: BUDGET.drawCalls, ok: s.calls <= BUDGET.drawCalls },
      tris: { value: s.tris, limit: BUDGET.triangles, ok: s.tris <= BUDGET.triangles },
    };
    s.budget.ok = s.budget.frameMs.ok && s.budget.calls.ok && s.budget.tris.ok;
    return s;
  },

  /** Determinism surface — `digest.mjs` hashes these. */
  digest() { return { streams: streamNames(), textures: textureKeys(), seed: 'chronoforge-dawn' }; },
  reseed() { resetStreams(); },

  /* The shared ctx, for tools that must BUILD a scene rather than photograph one.
     The Encounter Framing POC stages primitives on real terrain and measures
     occlusion during the push-in; post/probe/stats cannot do that from outside.
     Read-only by convention: this is a probe seam, not a lane's back door into
     shared core. A lane that mutates through it is violating CONTRACT.md §1. */
  get ctx() { return ctx; },

  /* ── not implemented in Phase 0 ──────────────────────────────────────────
     These THROW rather than returning a plausible-looking nothing. A stub that
     silently succeeds is how a probe reports green against a feature that does
     not exist, and that is worse than no probe at all.                      */
  battle() {
    throw new Error('__DAWN__.battle() is not implemented in Phase 0 — the battle lane lands in Tier 4 (Phase 6). See GAME_PLAN.md.');
  },
  teleport() {
    throw new Error('__DAWN__.teleport() is not implemented in Phase 0 — it needs the traversal lane, Tier 2 (Phase 4). See GAME_PLAN.md.');
  },
};
window.__DAWN__ = api;

/* ── go ──────────────────────────────────────────────────────────────────── */
api.setTime(num('hour', num('t', DAWN_HOUR)));
rig.apply(engine.camera, focus());
env.update(FIXED, focus());

// Compile before the first presented frame, so no capture ever photographs a
// half-compiled pipeline.
engine.renderer.compile(engine.scene, engine.camera);

const simSeek = num('sim', 0);
if (simSeek > 0) seekTo(simSeek);
else updateScene(FIXED);

if (params.get('shot')) api.setShot(params.get('shot'));

frame();

// Readiness is signalled only after several PRESENTED frames. Signalling on the
// first would let the harness screenshot through the boot backdrop.
let readyFrames = 0;
(function readyTick() {
  if (++readyFrames >= 6) {
    const boot = document.getElementById('boot');
    if (boot) { boot.style.opacity = '0'; setTimeout(() => boot.remove(), 400); }
    api.ready = true;
    document.body.dataset.ready = '1';
    bus.emit('ready', { version: api.version });
    return;
  }
  requestAnimationFrame(readyTick);
})();
